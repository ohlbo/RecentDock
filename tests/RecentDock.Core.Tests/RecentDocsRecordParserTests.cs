    [Fact]
    public void Parse_FolderBucketRecord_HasExpectedLength()
    {
        // Guards the fixture itself: a mistranscribed hex dump would silently make
        // the PIDL offset assertions below meaningless.
        Assert.Equal(130, FolderBucketRecord().Length);
        Assert.Equal(152, ChineseTextRecord().Length);
        Assert.Equal(162, PdfRecord().Length);
    }

    [Fact]
    public void Parse_ChineseName_DecodesCorrectly()
    {
        RecentDocRecord? record = RecentDocsRecordParser.Parse(ChineseTextRecord());

        Assert.NotNull(record);
        Assert.Equal("新建 文本文档.txt", record!.Name);
    }

    [Fact]
    public void Parse_ChineseName_FindsPidlAtNameTerminatorPlusTwo()
    {
        RecentDocRecord? record = RecentDocsRecordParser.Parse(ChineseTextRecord());

        Assert.NotNull(record);
        Assert.Equal(24, record!.NameFieldLength);
        Assert.Equal(24, record.PidlOffset);
    }

    [Fact]
    public void Parse_AsciiName_DecodesCorrectly()
    {
        RecentDocRecord? record = RecentDocsRecordParser.Parse(PdfRecord());

        Assert.NotNull(record);
        Assert.Equal("2512.15694v1.pdf", record!.Name);
        Assert.Equal(34, record.NameFieldLength);
        Assert.Equal(34, record.PidlOffset);
    }

    [Fact]
    public void Parse_FolderBucketRecord_DecodesCorrectly()
    {
        RecentDocRecord? record = RecentDocsRecordParser.Parse(FolderBucketRecord());

        Assert.NotNull(record);
        Assert.Equal("Internet", record!.Name);
        Assert.Equal(18, record.NameFieldLength);
        Assert.Equal(18, record.PidlOffset);
    }

    [Fact]
    public void Parse_MojibakeRegression_IsCaught()
    {
        // The exact wrong output the PowerShell decoder produced for this buffer.
        // If someone reintroduces a hand-rolled code-point loop, this fails.
        RecentDocRecord? record = RecentDocsRecordParser.Parse(ChineseTextRecord());

        Assert.NotNull(record);
        Assert.NotEqual("°ú ,c.txt", record!.Name);
        Assert.DoesNotContain('\u00B0', record.Name);
    }

    [Theory]
    [InlineData(new byte[0])]
    [InlineData(new byte[] { 0x41 })]
    [InlineData(new byte[] { 0x41, 0x00, 0x42 })]
    public void Parse_TooShortOrUnterminated_ReturnsNull(byte[] raw)
    {
        Assert.Null(RecentDocsRecordParser.Parse(raw));
    }

    [Fact]
    public void Parse_Null_ReturnsNull()
    {
        Assert.Null(RecentDocsRecordParser.Parse(null));
    }

    [Fact]
    public void Parse_NameContainingControlCharacter_ReturnsNull()
    {
        // 0x0001 is a control character, so the prefix is not a real name and the
        // derived PIDL offset must not be trusted.
        byte[] raw =
        {
            0x01, 0x00, 0x41, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00,
        };

        Assert.Null(RecentDocsRecordParser.Parse(raw));
    }

    [Fact]
    public void Parse_NameOnlyNoPidl_ReportsNoPidlOffset()
    {
        // Name field ends exactly at the end of the buffer: there is no room for a
        // PIDL, so the offset is reported as -1 instead of pointing past the end.
        byte[] raw = { 0x41, 0x00, 0x00, 0x00 };

        RecentDocRecord? record = RecentDocsRecordParser.Parse(raw);

        Assert.NotNull(record);
        Assert.Equal("A", record!.Name);
        Assert.Equal(-1, record.PidlOffset);
    }
