/// <summary>
/// RecentDocsRecordParser tests.
///
/// The fixtures below are verbatim hex dumps of a live RecentDocs key, so they
/// pin the parser to real data rather than to an assumed layout. Two traps are
/// covered explicitly:
///
///   * value 7 is a Chinese name. The original PowerShell decoder produced
///     "°ú ,c.txt" for it because -shl on a [byte] operand truncated the high
///     byte. Any regression to a hand-rolled code-point loop fails here.
///   * the PIDL offset must be nameTerminator + 2. A "plausible header" search
///     resolved nothing at all on these same buffers.
/// </summary>
public class RecentDocsRecordParserTests
{
